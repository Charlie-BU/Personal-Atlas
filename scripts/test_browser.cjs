/* Real-browser dropdown regression test. Pass a synthetic exported HTML path. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const http = require('node:http');
const { chromium } = require('playwright');
(async () => {
  const html = fs.readFileSync(process.argv[2]);
  const server = http.createServer((req, res) => { res.setHeader('Content-Type', 'text/html; charset=utf-8'); res.end(html); });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  let browser;
  try {
    browser = await chromium.launch({channel: process.env.ATLAS_BROWSER_CHANNEL || undefined});
    const page = await browser.newPage({viewport: {width: 1440, height: 900}, reducedMotion: 'reduce'});
    page.setDefaultTimeout(10000);
    const errors = [], external = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', req => { if (!req.url().startsWith('http://127.0.0.1:')) external.push(req.url()); });
    await page.goto('http://127.0.0.1:' + server.address().port);
    const trigger = page.locator('#relationTrigger');
    await trigger.click();
    await page.getByRole('option', {name: '关于', exact: true}).click();
    const options = page.getByRole('option');
    const another = options.filter({hasNotText: /^(全部关系|关于)$/}).first();
    await another.click();
    assert.equal(await page.locator('#relation option:checked').count(), 2);
    assert.equal(await page.locator('[role="option"][aria-selected="true"]').count(), 2);
    assert.ok((await trigger.innerText()).includes(', '));
    assert.equal(await page.locator('#relationMenu').evaluate(el => getComputedStyle(el).scrollbarWidth), 'none');
    await another.click();
    assert.equal(await trigger.getAttribute('aria-expanded'), 'true');
    await page.keyboard.press('End');
    assert.equal(await page.getByRole('option').last().evaluate(el => el === document.activeElement), true);
    await page.keyboard.press('Home');
    assert.equal(await page.getByRole('option').first().evaluate(el => el === document.activeElement), true);
    await page.keyboard.press('Escape');
    assert.equal(await page.getByRole('listbox').count(), 0);
    assert.equal(await trigger.evaluate(el => el === document.activeElement), true);
    await trigger.click();
    await page.locator('#search').click();
    assert.equal(await page.getByRole('listbox').count(), 0);
    await page.locator('#languageToggle').click();
    assert.equal(await page.locator('html').getAttribute('lang'), 'en');
    assert.equal(await trigger.innerText(), 'About');
    await page.reload();
    assert.equal(await page.locator('html').getAttribute('lang'), 'en');
    for (const width of [270, 269]) {
      await page.evaluate(width => panelWidth('left', width), width);
      const columns = await page.locator('.filter-grid').evaluate(el => getComputedStyle(el).gridTemplateColumns.split(' ').length);
      assert.equal(columns, width === 270 ? 2 : 1);
    }
    await page.evaluate(() => panelWidth('left', 270));
    await page.locator('#languageToggle').click();
    await trigger.click();
    if (process.env.ATLAS_SCREENSHOT) await page.screenshot({path: process.env.ATLAS_SCREENSHOT});
    await page.keyboard.press('Escape');
    await page.locator('#themeDark').click();
    await page.locator('#languageToggle').click();
    await trigger.click();
    if (process.env.ATLAS_SCREENSHOT) await page.screenshot({path: process.env.ATLAS_SCREENSHOT.replace('.png', '-dark.png')});
    await page.keyboard.press('Escape');
    await page.locator('#reset').click();
    assert.equal(await page.locator('#previousNode').isDisabled(), true);
    await page.locator('#results button').nth(0).click();
    const firstTitle = await page.locator('#detail h2').innerText();
    assert.equal(await page.locator('#previousNode').isDisabled(), true);
    await page.locator('#results button').nth(1).click();
    assert.equal(await page.locator('#previousNode').isEnabled(), true);
    await page.locator('#previousNode').click();
    assert.equal(await page.locator('#detail h2').innerText(), firstTitle);
    assert.equal(await page.locator('#previousNode').isDisabled(), true);

    await page.locator('#reset').click();
    await page.locator('#updatedStart').click();
    await page.getByRole('button', {name: 'Previous month'}).click();
    await page.getByRole('button', {name: '2026-09-04'}).click();
    await page.locator('#updatedEnd').click();
    await page.getByRole('button', {name: '2026-09-05'}).click();
    assert.ok(await page.evaluate(() => visible.length && visible.every(n => n.updated_at.startsWith('2026-09-05'))));
    await page.locator('#updatedStart').click();
    assert.equal(await page.getByRole('button', {name: '2026-09-06'}).isDisabled(), true);
    await page.keyboard.press('Escape');
    await page.locator('#reset').click();
    await page.locator('#kindTrigger').click();
    await page.getByRole('option', {name: 'Source', exact: true}).click();
    await page.keyboard.press('Escape');
    assert.equal(await page.evaluate(() => visible.length), 4);
    const drawn = await page.evaluate(() => {
      const calls = [];
      const original = ctx.fillText;
      ctx.fillText = text => calls.push(text);
      hover = visible[0].id;
      draw();
      ctx.fillText = original;
      return calls;
    });
    assert.ok(drawn.some(text => /^2026-\d{2}-\d{2} · .+/.test(text)));
    assert.equal(drawn.filter(text => /^2026-\d{2}-\d{2}$/.test(text)).length, 3);
    await page.locator('#results button').first().click();
    assert.match(await page.locator('#detail h2').innerText(), /^2026-\d{2}-\d{2} · /);
    await page.locator('#search').focus();
    assert.equal(await page.locator('#search').evaluate(el => getComputedStyle(el).outlineStyle), 'none');
    assert.equal(await page.locator('.search-box').evaluate(el => getComputedStyle(el).outlineStyle), 'none');
    assert.equal(await page.locator('.brand-icon img').getAttribute('src'), await page.locator('link[rel=icon]').getAttribute('href'));

    await page.emulateMedia({reducedMotion:'no-preference'});
    const panel = page.locator('#recordsPanel');
    await panel.locator('summary').click();
    await page.waitForFunction(() => !document.getElementById('recordsPanel').open);
    const animation = await panel.locator('summary').evaluate(el => {
      el.click();
      const effect = el.parentElement.getAnimations()[0]?.effect;
      return effect?.getKeyframes().map(frame => parseFloat(frame.height));
    });
    assert.ok(animation?.[1] > animation?.[0]);
    await page.waitForFunction(() => !document.getElementById('recordsPanel').getAnimations().length);
    await page.setViewportSize({width: 390, height: 844});
    await page.waitForFunction(() => !document.getElementById('filtersPanel').open);
    assert.deepEqual(errors, []);
    assert.deepEqual(external, []);
    console.log('Browser: dropdown selection, focus, keyboard, outside click, language persistence, 270/269px, themes and mobile passed.');
  } finally {
    if (browser) await browser.close();
    await new Promise(resolve => server.close(resolve));
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
